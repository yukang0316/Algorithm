# 1. input()으로 한 줄을 문자열로 읽어옵니다. (예: "20 30 10")
# 2. .split()으로 공백을 기준으로 문자열을 나눕니다. (예: ['20', '30', '10'])
# 3. map(int, ...)를 사용하여 리스트 안의 각 문자열을 정수로 변환합니다. (예: [20, 30, 10])
# 4. list(...)로 map 객체를 최종적으로 리스트로 변환하여 변수에 저장합니다.
numbers = list(map(int, input().split())) # 변수명을 'list' 대신 'numbers'로 바꾸는 것이 좋습니다. 'list'는 파이썬 내장 함수 이름이기 때문입니다.

# 5. 리스트를 오름차순으로 정렬합니다.
numbers.sort()

# 6. 정렬된 리스트에서 두 번째 인덱스(0부터 시작하므로 두 번째로 작은 값)에 해당하는 값을 출력합니다.
# 문제에서는 두 번째로 큰 정수를 출력하라고 했으므로, 정렬된 리스트의 두 번째 인덱스(list[1])가 됩니다.
# 20 30 10 -> 정렬 후 10 20 30 -> list[1]은 20
print(numbers[1])